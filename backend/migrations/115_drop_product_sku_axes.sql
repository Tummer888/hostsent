-- 115_drop_product_sku_axes.sql
--
-- 撤掉上游转售商品的「SKU 维度」功能（T4.8 反向）。
--
-- 决策变更（用户）：对接的上游商品（魔方财务）**一个商品就是一个 SPU**，
-- 不再在其下展开 SKU。原因：上游才是规格与价格的权威，本地拆出来的 SKU 会变成
-- 第二份真源 —— 上游改取值/改价时本地不跟随，需要人工重新生成与对账，
-- 维护成本高于收益。客户仍通过「客户可选配置项」在下单时选 CPU/内存，
-- 由上游按配置项计价（这条路径一直有效）。
--
-- 自营链路不受影响：自营商品的规格维度仍在规格模板的 option_selections.sku_axis 上，
-- 且自营的 SKU 由本地矩阵独立定价，不存在"跟随上游"的问题。
--
-- 幂等：DROP COLUMN IF EXISTS，且带索引判断不适用（该列无索引）。

ALTER TABLE products DROP COLUMN IF EXISTS sku_axes;
